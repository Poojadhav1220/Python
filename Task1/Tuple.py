# TUPLE FUNCTIONS AND METHODS

print("TUPLE FUNCTIONS AND METHODS")
t = (1,2,3,2,4,6,2,9,7)

# length of tuple
print("Length of tuple is:",len(t))

# largest element from tuple
print("Max is:",max(t))

# smallest element from tuple
print("Min is:",min(t))

# sum of all element
print("Sum is:",sum(t))

# count the specified value appers
print(t.count(2),"times appears")

# find the index of specified value
print("Index of value 7 is:",t.index(7))

